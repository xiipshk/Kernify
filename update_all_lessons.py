def find_topic_key(lesson):
    """Определяет ключ темы для шаблона объяснения по имени урока и темы."""
    name = lesson.name.lower()
    topic_name = lesson.subtopic.topic.name.lower() if lesson.subtopic and lesson.subtopic.topic else ''
    subtopic_name = lesson.subtopic.name.lower() if lesson.subtopic else ''

    combined = f'{name} {subtopic_name} {topic_name}'

    for keyword, key in TOPIC_KEYWORDS.items():
        if keyword in combined:
            return key

    return None

def get_explanations_for_topic(topic_key):
    """Возвращает список объяснений для темы или запасные общие."""
    if topic_key and topic_key in EXPLANATIONS:
        return EXPLANATIONS[topic_key]
    return GENERIC_EXPLANATIONS

def update_lesson_content(lesson):
    """Добавляет введение и объяснения в контент урока."""
    content = lesson.content if lesson.content else []
    if not isinstance(content, list):
        return False

    topic_key = find_topic_key(lesson)
    explanations = get_explanations_for_topic(topic_key)

    new_content = []
    code_block_index = 0

    first_block = content[0] if content else None

    # Добавляем введение после первого heading, если его нет
    if first_block and first_block.get('type') == 'heading':
        new_content.append(first_block)
        # Проверяем, есть ли уже существенное введение (текст > 150 символов в первых 3 блоках)
        has_substantial_intro = any(
            b.get('type') == 'text' and len(b.get('content', '')) > 150
            for b in content[1:4]
        )
        if not has_substantial_intro:
            intro_text = (
                f'В этом уроке вы изучите {lesson.name.lower()}. '
                f'Мы разберём основные концепции, посмотрим на примеры кода '
                f'и обсудим, где и зачем это применяется на практике.'
            )
            new_content.append({
                'type': 'text',
                'content': intro_text,
            })
        start_idx = 1
    else:
        start_idx = 0
        # Если нет heading, добавляем введение в начало
        if not any(
            b.get('type') == 'text' and len(b.get('content', '')) > 150
            for b in content[:3]
        ):
            intro_text = (
                f'В этом уроке вы изучите {lesson.name.lower()}. '
                f'Мы разберём основные концепции, посмотрим на примеры кода '
                f'и обсудим, где и зачем это применяется на практике.'
            )
            new_content.append({
                'type': 'text',
                'content': intro_text,
            })

    # Обрабатываем остальные блоки
    for i in range(start_idx, len(content)):
        block = content[i]
        new_content.append(block)

        # После каждого кода добавляем объяснение
        if block.get('type') == 'code':
            explanation_idx = code_block_index % len(explanations)
            heading, text = explanations[explanation_idx]
            new_content.append({
                'type': 'heading',
                'level': 3,
                'content': heading,
            })
            new_content.append({
                'type': 'text',
                'content': text,
            })
            code_block_index += 1

    # Проверяем, изменился ли контент
    if len(new_content) != len(content):
        lesson.content = new_content
        lesson.save(update_fields=['content', 'updated_at'])
        return True

    return False

# --- Main execution ---
updated = 0
total = 0
skipped_no_change = 0

for lang in ProgrammingLanguage.objects.filter(status='published').order_by('order', 'name'):
    progs = CourseProgram.objects.filter(language=lang, status='published').order_by('order')
    for p in progs:
        topics = Topic.objects.filter(program=p, status='published').order_by('order')
        for t in topics:
            subs = SubTopic.objects.filter(topic=t, status='published').order_by('order')
            for s in subs:
                lessons = Lesson.objects.filter(subtopic=s, status='published').order_by('order')
                for l in lessons:
                    total += 1
                    if update_lesson_content(l):
                        updated += 1
                        print(f'  [UPDATED] {lang.name} / {p.name} / {t.name} / {s.name} / {l.name}')
                    else:
                        skipped_no_change += 1

print(f'\n=== Готово: обновлено {updated} из {total} уроков (пропущено без изменений: {skipped_no_change}) ===')