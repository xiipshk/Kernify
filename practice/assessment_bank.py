def build_options(texts, correct_index):
    return [
        {'text': text, 'correct': i == correct_index}
        for i, text in enumerate(texts)
    ]


# Правильный ответ для каждого вопроса стоит первым во входных данных,
# поэтому перемешиваем варианты детерминированно (seed = язык + порядок),
# чтобы тесты не повторялись с одинаковым порядком ответов.
def seed_questions():
    """Возвращает список готовых к сохранению вопросов по всем языкам."""
    import random

    result = []
    for language_slug, items in BANK.items():
        for index, (topic_label, question, options, correct_index, explanation) in enumerate(items, start=1):
            rng = random.Random(f'{language_slug}-{index}')
            built = build_options(options, correct_index)
            rng.shuffle(built)
            result.append({
                'language_slug': language_slug,
                'order': index,
                'topic_label': topic_label,
                'question': question,
                'options': built,
                'explanation': explanation,
                'difficulty': 1 + (index - 1) // 7,
            })
    return result
