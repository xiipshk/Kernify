def main():
    errors = []
    changed = 0
    for rel, pairs in REPL.items():
        path = BASE + rel
        with open(path, encoding='utf-8') as fh:
            raw = fh.read()
        for old, new, expected in pairs:
            found = raw.count(old)
            if found != expected:
                errors.append(f'{rel}: {old!r} встретился {found} раз, ожидалось {expected}')
                continue
            raw = raw.replace(old, new)
            changed += found
        with open(path, 'w', encoding='utf-8') as fh:
            fh.write(raw)
        try:
            json.loads(raw)
        except json.JSONDecodeError as exc:
            errors.append(f'{rel}: битый JSON после замены ({exc})')

    print(f'Заменено вхождений: {changed}')
    if errors:
        print('Ошибки:')
        for e in errors:
            print('  -', e)
        sys.exit(1)


if __name__ == '__main__':
    main()
